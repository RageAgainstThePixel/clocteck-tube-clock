#!/bin/sh
# Writes firmware/tubeclock/secrets.h from the repo's .env. The header is git-ignored and the values
# are never printed.
set -eu
fw=$(cd "$(dirname "$0")/.." && pwd)
env_file="$fw/../.env"
out="$fw/tubeclock/secrets.h"

[ -f "$env_file" ] || { echo "missing $env_file" >&2; exit 1; }

# Reads KEY from .env: drops CR, surrounding quotes and everything up to the first '='.
get() {
  value=$(grep -E "^$1=" "$env_file" | tail -n 1 | cut -d= -f2- | tr -d '\r')
  value=${value#\"}; value=${value%\"}
  printf '%s' "$value"
}

# Escapes a value for a C string literal.
c_string() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

ssid=$(get FW_WIFI_SSID)
password=$(get FW_WIFI_PASSWORD)
token=$(get FW_API_TOKEN)
hostname=$(get FW_HOSTNAME)
[ -n "$hostname" ] || hostname=tubeclock

for key in FW_WIFI_SSID FW_WIFI_PASSWORD FW_API_TOKEN; do
  [ -n "$(get "$key")" ] || { echo "$key is empty in .env" >&2; exit 1; }
done

umask 077
cat > "$out" <<EOF
// Generated by scripts/gen-secrets.sh from .env. Do not commit.
#pragma once
static const char kWifiSsid[] = "$(c_string "$ssid")";
static const char kWifiPassword[] = "$(c_string "$password")";
static const char kApiToken[] = "$(c_string "$token")";
static const char kHostname[] = "$(c_string "$hostname")";
EOF
echo "wrote $out"
